package ddolite.tools.formlayout

/**
 * Writes the layout of a form as Markdown: for each container, its rows and columns and the
 * controls in them; then the menus; then the code lines that move controls at run time.
 *
 * The report is the starting point for a form's F0 inventory (PLAN.md §8.1): it says what's
 * where, so the Compose screen can use the same rows and columns.
 */
fun layoutReport(formFile: String, file: FrmFile, root: PlacedControl, imageNames: List<String>): String {
    val out = StringBuilder()
    val form = file.form
    out.append("# ").append(form.name).append(" layout\n\n")
    out.append("Generated by `tools/form-layout` from `").append(formFile).append("`; don't edit by hand.\n")
    out.append("Positions are pixels at 100% scaling (twips ÷ ").append(TWIPS_PER_PIXEL)
        .append("), measured from the form's client area. Edges within ").append(ALIGN_TOLERANCE)
        .append(" px count as one row or column.\n\n")
    out.append("- Caption: ").append(form.caption ?: "").append("\n")
    out.append("- Client size: ").append(root.bounds.width).append(" × ").append(root.bounds.height).append(" px\n")
    if (imageNames.isNotEmpty()) {
        out.append("- Wireframes:")
        for (name in imageNames) {
            out.append(" [").append(name).append("](").append(name).append(")")
        }
        out.append("\n")
    }
    out.append("\n")
    writeContainer(out, root)

    val menus = ArrayList<FrmControl>()
    for (child in form.children) {
        if (child.isMenu) {
            menus.add(child)
        }
    }
    if (menus.isNotEmpty()) {
        out.append("## Menus\n\n")
        for (menu in menus) {
            writeMenu(out, menu, 0)
        }
        out.append("\n")
    }

    val nonVisual = ArrayList<FrmControl>()
    collectNonVisual(form, nonVisual)
    if (nonVisual.isNotEmpty()) {
        out.append("## Non-visual controls\n\n")
        for (control in nonVisual) {
            out.append("- `").append(control.displayName).append("` ").append(shortType(control.type))
            val interval = control.properties["Interval"]
            if (interval != null) {
                out.append(", Interval ").append(interval).append(" ms")
            }
            out.append(" (.frm line ").append(control.line).append(")\n")
        }
        out.append("\n")
    }

    val moves = findRuntimeMoves(file)
    out.append("## Moved or resized at run time\n\n")
    if (moves.isEmpty()) {
        out.append("None found: the design-time layout is the real one.\n")
    } else {
        out.append("The positions above are only where these start; the code changes them.\n\n")
        out.append("| .frm line | Target | Code |\n|---|---|---|\n")
        for (move in moves) {
            out.append("| ").append(move.line).append(" | `").append(move.target).append("` | `")
                .append(move.code.replace("|", "\\|")).append("` |\n")
        }
    }
    return out.toString()
}

/** One section per container, depth first, with its grid and a table of its children. */
private fun writeContainer(out: StringBuilder, placed: PlacedControl) {
    val grid = placed.grid
    if (grid == null) {
        return
    }
    val b = placed.bounds
    out.append("## ").append(containerPath(placed)).append("\n\n")
    out.append(shortType(placed.control.type)).append(" at (").append(b.left).append(", ").append(b.top)
        .append("), ").append(b.width).append(" × ").append(b.height).append(" px")
    if (!placed.control.startsVisible) {
        out.append(", starts hidden")
    }
    out.append(".\n\n")
    out.append("- Columns (left edges): ").append(numbered("c", grid.cols)).append("\n")
    out.append("- Rows (top edges): ").append(numbered("r", grid.rows)).append("\n\n")
    out.append("| Row | Col | Control | Type | Caption | Left, Top | Size | Notes |\n")
    out.append("|---|---|---|---|---|---|---|---|\n")
    val sorted = ArrayList(placed.children)
    sorted.sortWith(compareBy<PlacedControl>({ it.row }, { it.col }))
    for (child in sorted) {
        val cb = child.bounds
        out.append("| r").append(child.row)
        if (child.rowSpan > 1) {
            out.append("–r").append(child.row + child.rowSpan - 1)
        }
        out.append(" | c").append(child.col)
        if (child.colSpan > 1) {
            out.append("–c").append(child.col + child.colSpan - 1)
        }
        out.append(" | `").append(child.control.displayName).append("` | ").append(shortType(child.control.type))
        out.append(" | ").append(cleanCaption(child.control.caption))
        out.append(" | ").append(cb.left).append(", ").append(cb.top)
        out.append(" | ").append(cb.width).append(" × ").append(cb.height)
        out.append(" | ").append(notes(child)).append(" |\n")
    }
    if (grid.nearMisses.isNotEmpty()) {
        out.append("\nNearly aligned (probably meant to line up):\n\n")
        for (miss in grid.nearMisses) {
            out.append("- ").append(miss).append("\n")
        }
    }
    out.append("\n")
    for (child in placed.children) {
        writeContainer(out, child)
    }
}

private fun notes(placed: PlacedControl): String {
    val parts = ArrayList<String>()
    if (!placed.control.startsVisible) {
        parts.add("hidden")
    }
    if (placed.children.isNotEmpty()) {
        parts.add("container, see below")
    }
    parts.add(".frm line " + placed.control.line)
    return parts.joinToString("; ")
}

/** "frmEnhancements › picTab(1) › fraTreeSelection". */
private fun containerPath(placed: PlacedControl): String {
    val names = ArrayList<String>()
    var p: PlacedControl? = placed
    while (p != null) {
        names.add(0, p.control.displayName)
        p = p.parent
    }
    return names.joinToString(" › ")
}

private fun numbered(prefix: String, values: List<Int>): String {
    val parts = ArrayList<String>()
    for (i in values.indices) {
        parts.add(prefix + i + "=" + values[i])
    }
    return parts.joinToString(", ")
}

private fun cleanCaption(caption: String?): String {
    if (caption == null || caption.contains(".frx")) {
        return ""
    }
    return caption.replace("|", "\\|")
}

private fun writeMenu(out: StringBuilder, menu: FrmControl, level: Int) {
    for (i in 0 until level) {
        out.append("  ")
    }
    out.append("- `").append(menu.displayName).append("` ").append(menu.caption ?: "")
    if (!menu.startsVisible) {
        out.append(" (hidden: a pop-up menu)")
    }
    out.append("\n")
    for (child in menu.children) {
        writeMenu(out, child, level + 1)
    }
}

private fun collectNonVisual(control: FrmControl, into: MutableList<FrmControl>) {
    for (child in control.children) {
        if (child.isNonVisual && !child.isMenu) {
            into.add(child)
        }
        if (!child.isMenu) {
            collectNonVisual(child, into)
        }
    }
}
